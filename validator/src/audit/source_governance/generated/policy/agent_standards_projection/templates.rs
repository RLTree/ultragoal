const SCRIPT_PROJECTIONS: &[&str] = &[
    "scripts/agent_standards_validation/__init__.py",
    "scripts/agent_standards_validation/command.py",
    "scripts/agent_standards_validation/contracts.py",
    "scripts/check-agent-standards",
];

pub(super) fn render(request: ProjectionRequest<'_>) -> Result<Vec<u8>, &'static str> {
    let [source] = request.canonical_sources else {
        return Err("template_source_set_invalid");
    };
    let source = source.as_str();
    if request.output != format!("templates/{source}") {
        return Err("template_output_mapping_invalid");
    }
    let bytes = request
        .sources
        .get(source)
        .ok_or("template_source_missing")?
        .bytes
        .as_slice();
    if SCRIPT_PROJECTIONS.contains(&source) {
        return Ok(bytes.to_vec());
    }
    if !ROOT_DOCUMENTS.contains(&source) && !STANDARD_DOCUMENTS.contains(&source) {
        return Err("template_source_unsupported");
    }
    let marker = format!(
        "<!-- @generated by scripts/project-agent-standards; source: {source}; do not edit -->\n\n"
    );
    let mut output = marker.into_bytes();
    output.extend_from_slice(bytes);
    Ok(output)
}
